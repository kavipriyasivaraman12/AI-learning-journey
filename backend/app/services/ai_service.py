"""
AI Service Layer.

Encapsulates all interactions with the Google Gemini API using the official Google GenAI SDK.
Enforces structured JSON generation, token conservation, strict schema validation,
and seamless fallback recovery for offline/missing API key scenarios.
"""

import json
import logging
from typing import List, Optional, Dict, Any
from fastapi import HTTPException, status
from pydantic import BaseModel, Field

from app.config import settings

logger = logging.getLogger("ai_service")


# Pydantic Schemas for AI Structured Output Validation
class AIRoadmapTopic(BaseModel):
    """Schema for individual topic generated by AI."""
    title: str = Field(..., description="Concise, clear topic title")
    description: str = Field(..., description="Summary of skills and concepts covered")
    sequence_order: int = Field(..., description="Prerequisite order (1, 2, 3...)")
    difficulty: str = Field("Beginner", description="Beginner, Intermediate, or Advanced")
    estimated_minutes: int = Field(60, description="Estimated study duration in minutes")


class AIRoadmapResponse(BaseModel):
    """Schema for complete structured learning roadmap generated by AI."""
    title: str = Field(..., description="Title of the learning roadmap")
    description: str = Field(..., description="High level roadmap summary")
    topics: List[AIRoadmapTopic] = Field(..., min_length=1, description="List of ordered topics")


class AITopicContentResponse(BaseModel):
    """Schema for structured educational topic material generated by AI."""
    summary: str = Field(..., description="2-3 sentence overview of the topic")
    explanation: str = Field(..., description="Detailed, structured explanation with a real-world analogy")
    code_examples: str = Field(..., description="Working, well-commented code snippets")
    common_mistakes: str = Field(..., description="Common pitfalls, anti-patterns, and debugging tips")
    key_takeaways: str = Field(..., description="Summary bullet points for quick retention")


class AIAssessmentQuestion(BaseModel):
    """Schema for individual assessment question."""
    question_text: str = Field(..., description="Multiple choice question prompt")
    options: List[str] = Field(..., min_length=2, max_length=5, description="List of answer choices")
    correct_option_index: int = Field(..., ge=0, description="0-indexed integer of the correct option")
    explanation: str = Field(..., description="Brief explanation why the answer is correct")
    concept_tag: str = Field(..., description="Specific concept or sub-topic tested, e.g. 'Polymorphism'")


class AIAssessmentResponse(BaseModel):
    """Schema for complete topic assessment quiz generated by AI."""
    title: str = Field(..., description="Assessment quiz title")
    passing_score_percentage: int = Field(70, ge=50, le=100, description="Passing score threshold percentage")
    questions: List[AIAssessmentQuestion] = Field(..., min_length=2, description="List of assessment questions")


class AITutorResponse(BaseModel):
    """Schema for structured AI Tutor response to a student question."""
    explanation: str = Field(..., description="Educational explanation tailored to student skill level")
    code_example: Optional[str] = Field(None, description="Illustrative code example if relevant")
    common_mistake: Optional[str] = Field(None, description="Common pitfall related to the question")
    practice_question: Optional[str] = Field(None, description="Quick practice or self-check question")
    is_topic_related: bool = Field(True, description="Whether the question is related to the current topic")


class AIService:

    """
    AI Service Adapter providing structured generation and token management.
    Can be swapped or extended for different models (e.g. Gemma, local LLMs).
    """

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model_name = "gemini-3.1-flash-lite"
        self._client = None

        if self.api_key and self.api_key.strip():
            try:
                from google import genai
                self._client = genai.Client(api_key=self.api_key)
            except Exception as e:
                logger.warning(f"Could not initialize Google GenAI Client: {e}")
                self._client = None

    def is_available(self) -> bool:
        """Returns True if the Gemini client is initialized with an API key."""
        if self._client is None:
            key = settings.GEMINI_API_KEY or self.api_key
            if key and key.strip():
                try:
                    from google import genai
                    self.api_key = key.strip()
                    self._client = genai.Client(api_key=self.api_key)
                except Exception as e:
                    logger.warning(f"Could not initialize Google GenAI Client: {e}")
        return self._client is not None

    def generate_learning_roadmap(
        self,
        goal_title: str,
        profile_context: Optional[Dict[str, Any]] = None,
        learning_level: str = "beginner",
    ) -> AIRoadmapResponse:
        """
        Generates an individualized 25-30 topic learning roadmap for a student.
        """
        if not self.is_available():
            logger.info(f"Gemini API key not configured. Using domain template fallback for {learning_level} roadmap.")
            return self._fallback_roadmap(goal_title, learning_level)

        context_parts = [f"Target Goal: {goal_title}", f"Learning Level: {learning_level.upper()}"]
        if profile_context:
            if "education_level" in profile_context:
                context_parts.append(f"Education: {profile_context['education_level']}")
            if "weekly_hours_available" in profile_context:
                context_parts.append(f"Weekly Time: {profile_context['weekly_hours_available']} hrs/week")
            if "preferred_learning_style" in profile_context:
                context_parts.append(f"Style: {profile_context['preferred_learning_style']}")

        learner_context_str = "; ".join(context_parts)

        system_instruction = (
            f"You are an expert curriculum designer. Generate a comprehensive, prerequisite-ordered "
            f"learning roadmap containing between 25 and 30 distinct, logically progressing topics "
            f"for a {learning_level.upper()} level student aiming for '{goal_title}'.\n"
            f"Each topic must represent an incremental milestone with clear dependencies.\n"
            f"Respond strictly in valid JSON matching this schema:\n"
            f'{{"title": string, "description": string, "topics": [{{"title": string, "description": string, "sequence_order": int, "difficulty": string, "estimated_minutes": int}}]}}'
        )

        user_prompt = f"Create a comprehensive 25-30 topic personalized learning roadmap for profile: {learner_context_str}."

        try:
            from google.genai import types

            response = self._client.models.generate_content(
                model=self.model_name,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    response_mime_type="application/json",
                    temperature=0.2,
                ),
            )

            raw_text = response.text.strip()
            parsed_data = json.loads(raw_text)
            validated_roadmap = AIRoadmapResponse.model_validate(parsed_data)
            if len(validated_roadmap.topics) >= 1:
                return validated_roadmap
            # If AI returned no topics, fallback to comprehensive 25-topic template
            logger.warning(f"Gemini returned empty topics. Merging with curated fallback.")
            return self._fallback_roadmap(goal_title, learning_level)

        except Exception as e:
            logger.error(f"Gemini API call or JSON validation failed: {e}. Activating fallback.")
            return self._fallback_roadmap(goal_title, learning_level)

    def generate_topic_content(
        self,
        topic_title: str,
        goal_title: str,
        profile_context: Optional[Dict[str, Any]] = None,
    ) -> AITopicContentResponse:
        """
        Generates deep, topic-specific educational content:
        Summary, explanation with real-world analogy, annotated code snippet, common mistakes, and takeaways.
        """
        if not self.is_available():
            logger.info(f"Gemini API key not configured. Using domain template fallback for topic '{topic_title}'.")
            return self._fallback_topic_content(topic_title, goal_title)

        skill_level = profile_context.get("current_skill_level", "Beginner") if profile_context else "Beginner"
        learning_style = profile_context.get("preferred_learning_style", "Practical") if profile_context else "Practical"

        system_instruction = (
            "You are a friendly, senior software engineer and computer science tutor. "
            "Explain the technical topic clearly and thoroughly for the specified learner level. "
            "Always include a real-world analogy, clean code snippets with explanations, "
            "common beginner pitfalls/bugs, and bulleted takeaways. "
            "Respond strictly in valid JSON with keys: 'summary', 'explanation', 'code_examples', 'common_mistakes', 'key_takeaways'."
        )

        user_prompt = (
            f"Topic: {topic_title}\n"
            f"Overarching Goal: {goal_title}\n"
            f"Learner Skill Level: {skill_level}\n"
            f"Learner Preferred Style: {learning_style}\n"
            "Provide structured educational content for this topic."
        )

        try:
            from google.genai import types

            response = self._client.models.generate_content(
                model=self.model_name,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    response_mime_type="application/json",
                    temperature=0.3,
                ),
            )

            raw_text = response.text.strip()
            parsed_data = json.loads(raw_text)
            validated_content = AITopicContentResponse.model_validate(parsed_data)
            return validated_content

        except Exception as e:
            logger.error(f"Gemini topic content generation failed: {e}. Activating fallback.")
            return self._fallback_topic_content(topic_title, goal_title)

    def _fallback_roadmap(self, goal_title: str, learning_level: str = "beginner") -> AIRoadmapResponse:
        """Deterministic 25-topic fallback for roadmap generation."""
        from app.services.learning_service import _get_default_topics_for_goal

        topics_data = _get_default_topics_for_goal(goal_title, learning_level)
        roadmap_topics: List[AIRoadmapTopic] = []

        for idx, item in enumerate(topics_data, start=1):
            roadmap_topics.append(
                AIRoadmapTopic(
                    title=item["title"],
                    description=item["description"],
                    sequence_order=idx,
                    difficulty=item.get("difficulty", learning_level.capitalize()),
                    estimated_minutes=item.get("minutes", 50),
                )
            )

        return AIRoadmapResponse(
            title=f"{goal_title} {learning_level.capitalize()} Learning Journey",
            description=f"Curated 25-topic step-by-step learning roadmap for mastering {goal_title} at the {learning_level.capitalize()} level.",
            topics=roadmap_topics,
        )

    def _fallback_topic_content(self, topic_title: str, goal_title: str) -> AITopicContentResponse:
        """Deterministic fallback for topic educational content."""
        return AITopicContentResponse(
            summary=f"Core concepts, syntax, and principles of {topic_title} in the context of {goal_title}.",
            explanation=(
                f"### Understanding {topic_title}\n\n"
                f"{topic_title} is an essential foundation for {goal_title}. "
                "Think of it like building the foundation of a house: before you can add complex features, "
                "you must understand how the fundamental building blocks interconnect and execute.\n\n"
                "Key concepts include understanding memory layout, execution flow, scope, and encapsulation."
            ),
            code_examples=(
                f"# Example: Core demonstration of {topic_title}\n\n"
                "def demonstrate_concept():\n"
                "    \"\"\"Illustrates standard usage pattern.\"\"\"\n"
                f"    data = ['item1', 'item2', 'item3']\n"
                "    result = [item.upper() for item in data]\n"
                "    return result\n\n"
                "if __name__ == '__main__':\n"
                "    print(demonstrate_concept())\n"
            ),
            common_mistakes=(
                f"1. **Scope Confusion:** Modifying variables outside the local namespace without proper scoping.\n"
                f"2. **Type Incompatibility:** Assuming automatic conversion without explicit parsing.\n"
                f"3. **Missing Error Handling:** Failing to guard against null/empty values or missing keys."
            ),
            key_takeaways=(
                f"• {topic_title} forms a foundational pillar for {goal_title}.\n"
                f"• Always write modular, readable code and verify edge cases.\n"
                f"• Practice with small exercises before moving to complex projects."
            ),
        )

    def generate_topic_assessment(
        self,
        topic_title: str,
        goal_title: str,
        profile_context: Optional[Dict[str, Any]] = None,
    ) -> AIAssessmentResponse:
        """
        Generates a 15-question multiple-choice assessment quiz bank for a topic.
        Considers student skill level to ensure appropriate difficulty and diverse question types.
        """
        if not self.is_available():
            logger.info(f"Gemini API key not configured. Using deterministic fallback 15-question assessment for '{topic_title}'.")
            return self._fallback_topic_assessment(topic_title, goal_title)

        skill_level = profile_context.get("current_skill_level", "Beginner") if profile_context else "Beginner"

        system_instruction = (
            "You are an expert computer science professor creating an objective 15-question mastery assessment quiz. "
            "Generate exactly 15 distinct, high-quality multiple-choice questions testing:\n"
            "- Conceptual foundations (4 questions)\n"
            "- Code output & syntax analysis (4 questions)\n"
            "- Common bug detection & debugging (4 questions)\n"
            "- Real-world scenario application (3 questions)\n"
            "Each question must have 4 distinct options, a 0-indexed correct_option_index, an educational explanation, "
            "and a concept_tag. Respond strictly in valid JSON matching schema:\n"
            '{"title": string, "passing_score_percentage": int, "questions": [{"question_text": string, "options": [string], "correct_option_index": int, "explanation": string, "concept_tag": string}]}'
        )

        user_prompt = (
            f"Topic: {topic_title}\n"
            f"Learning Goal: {goal_title}\n"
            f"Target Student Skill Level: {skill_level}\n"
            "Generate a 15-question mastery assessment quiz."
        )

        try:
            from google.genai import types

            response = self._client.models.generate_content(
                model=self.model_name,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    response_mime_type="application/json",
                    temperature=0.2,
                ),
            )

            raw_text = response.text.strip()
            parsed_data = json.loads(raw_text)
            validated_assessment = AIAssessmentResponse.model_validate(parsed_data)
            if len(validated_assessment.questions) >= 1:
                return validated_assessment
            return self._fallback_topic_assessment(topic_title, goal_title, skill_level)

        except Exception as e:
            logger.error(f"Gemini assessment generation failed: {e}. Activating fallback.")
            return self._fallback_topic_assessment(topic_title, goal_title, skill_level)


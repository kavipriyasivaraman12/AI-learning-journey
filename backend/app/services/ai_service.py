    def ask_topic_tutor(
        self,
        topic_title: str,
        goal_title: str,
        student_level: str,
        question: str,
        topic_description: str = "",
        topic_difficulty: str = "Beginner",
        topic_content: Optional[Dict[str, str]] = None,
        conversation_history: Optional[List[Any]] = None,
        topic_summary: Optional[str] = None,
    ) -> AITutorResponse:
        """
        Interactive Gemini AI Topic Tutor answering a student question scoped to the current topic.
        Grounded in the current topic context, description, difficulty, student level, goal,
        and actual lesson content, while maintaining multi-turn context from conversation history.
        """
        if not self.is_available():
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Gemini API key is not configured. Please add GEMINI_API_KEY to your backend .env file to enable the AI Tutor.",
            )

        # Precise tutor system instruction
        system_instruction = (
            "You are an AI learning tutor inside a personalized learning platform.\n\n"
            "Your job is to help the student understand the current lesson.\n\n"
            "Current topic and supplied lesson content are the primary context.\n\n"
            "Answer clearly, accurately and at the student's learning level.\n\n"
            "Use the conversation history to understand follow-up questions.\n\n"
            "If the student asks for clarification, explain the same concept in a different and simpler way.\n\n"
            "Do not pretend to know information that is unsupported or uncertain.\n\n"
            "Do not invent facts.\n\n"
            "Stay relevant to the current learning topic.\n\n"
            "If a question is unrelated to the current topic, politely redirect the student to the current lesson.\n\n"
            "Your goal is understanding, not just producing an answer.\n\n"
            "TUTOR BEHAVIOR GUIDELINES:\n"
            "1. Grounding: The supplied lesson content is your primary educational context. Do not answer as a generic chatbot.\n"
            "2. Follow-Up Understanding: If the student asks 'why?', 'explain that again', 'give another example', 'what is the difference?', or 'I didn't understand', use the conversation history to resolve what 'that' refers to and maintain continuous conversational context.\n"
            "3. Flexible Response Formatting: Naturally choose the most appropriate structure for the question:\n"
            "   - Simple question: short, direct explanation + intuitive example.\n"
            "   - Conceptual question: clear explanation + example + key takeaways.\n"
            "   - Programming/technical question: explanation + annotated working code snippet + brief explanation of the code.\n"
            "   - 'I don't understand': re-explain using simpler language, fresh analogy, and a different example.\n"
            "   - Avoid unnecessarily long or repetitive boilerplate.\n"
            "4. Unrelated Queries: If the question is outside the scope of the current topic (e.g. food recipes, sports, celebrity gossip), set is_topic_related=false, and provide a polite redirect asking them to focus on the current lesson.\n"
            "5. Output Schema: Respond strictly with valid JSON matching:\n"
            '{"explanation": string, "is_topic_related": bool, "code_example": string or null, "common_mistake": string or null, "practice_question": string or null}'
        )

        prompt_parts = [
            "=== CURRENT LEARNING CONTEXT ===",
            f"Topic Title: {topic_title}",
            f"Topic Description: {topic_description or 'N/A'}",
            f"Topic Difficulty: {topic_difficulty}",
            f"Student Learning Level: {student_level}",
            f"Student Career Goal: {goal_title}",
        ]

        # Inject actual lesson content for primary educational grounding
        if topic_content:
            prompt_parts.append("\n=== SUPPLIED LESSON CONTENT (PRIMARY EDUCATIONAL GROUNDING) ===")
            if topic_content.get("summary"):
                prompt_parts.append(f"[Overview]\n{topic_content['summary']}")
            if topic_content.get("explanation"):
                prompt_parts.append(f"[Concept Explanation]\n{topic_content['explanation']}")
            if topic_content.get("code_examples"):
                prompt_parts.append(f"[Code Examples]\n{topic_content['code_examples']}")
            if topic_content.get("common_mistakes"):
                prompt_parts.append(f"[Common Mistakes]\n{topic_content['common_mistakes']}")
            if topic_content.get("key_takeaways"):
                prompt_parts.append(f"[Key Takeaways]\n{topic_content['key_takeaways']}")
        elif topic_summary:
            prompt_parts.append(f"\n=== SUPPLIED LESSON SUMMARY ===\n{topic_summary}")

        # Inject controlled recent conversation history (last 8 messages / 4 turns)
        if conversation_history:
            recent_history = conversation_history[-8:]
            prompt_parts.append("\n=== RECENT CONVERSATION HISTORY ===")
            for msg in recent_history:
                role = msg.get("role") if isinstance(msg, dict) else getattr(msg, "role", "user")
                role_label = "Student" if role == "user" else "Tutor"
                content_text = msg.get("content") if isinstance(msg, dict) else getattr(msg, "content", "")
                if content_text:
                    prompt_parts.append(f"{role_label}: {content_text.strip()[:600]}")

        prompt_parts.append("\n=== CURRENT STUDENT QUESTION ===")
        prompt_parts.append(f"Student: {question.strip()}")

        from google.genai import types

        # Candidate models to try in case of model retirement (404) or transient high-demand spikes (503)
        candidate_models = [self.model_name]
        for fallback_m in ["gemini-3.1-flash-lite", "gemini-3.5-flash-lite", "gemini-3.8-flash"]:
            if fallback_m not in candidate_models:
                candidate_models.append(fallback_m)

        last_exception = None
        for current_model in candidate_models:
            try:
                logger.info(f"Calling Gemini Topic Tutor using model '{current_model}'...")
                response = self._client.models.generate_content(
                    model=current_model,
                    contents="\n".join(prompt_parts),
                    config=types.GenerateContentConfig(
                        system_instruction=system_instruction,
                        response_mime_type="application/json",
                        temperature=0.3,
                    ),
                )

                if not response or not hasattr(response, "text") or not response.text or not response.text.strip():
                    raise HTTPException(
                        status_code=status.HTTP_502_BAD_GATEWAY,
                        detail="AI Tutor returned an empty response from Gemini. Please click Retry.",
                    )

                raw_text = response.text.strip()
                if raw_text.startswith("```"):
                    parts = raw_text.split("```", 2)
                    if len(parts) >= 2:
                        raw_text = parts[1]
                    if raw_text.startswith("json"):
                        raw_text = raw_text[4:].strip()
                    if raw_text.endswith("```"):
                        raw_text = raw_text[:-3].strip()

                try:
                    parsed_data = json.loads(raw_text)
                except json.JSONDecodeError as json_err:
                    logger.error(f"Failed to parse Gemini tutor JSON: {json_err}. Raw text: {raw_text[:200]}")
                    raise HTTPException(
                        status_code=status.HTTP_502_BAD_GATEWAY,
                        detail="AI Tutor received an invalid response format from Gemini. Please click Retry.",
                    )

                # Update default model to the one that succeeded
                self.model_name = current_model
                return AITutorResponse.model_validate(parsed_data)

            except HTTPException:
                raise
            except Exception as e:
                last_exception = e
                err_str = str(e)
                logger.warning(f"Model '{current_model}' failed with {type(e).__name__}: {err_str[:200]}. Trying next candidate if available...")
                # If it's a 404 or 503 on this specific model, proceed to the next candidate
                if "404" in err_str or "not_found" in err_str.lower() or "503" in err_str or "unavailable" in err_str.lower():
                    continue
                # For auth/rate-limit errors, do not loop through other models
                break

        # If all candidate models failed, construct transparent sanitized error
        e = last_exception or Exception("All candidate Gemini models failed")
        err_msg = str(e)
        # Strictly sanitize API key from any error message
        api_key_val = self.api_key or settings.GEMINI_API_KEY
        if api_key_val and len(api_key_val) > 4:
            err_msg = err_msg.replace(api_key_val, "[REDACTED_API_KEY]")

        logger.error(f"All Gemini topic tutor model attempts failed. Last error [{type(e).__name__}]: {err_msg}")

        err_lower = err_msg.lower()
        if "timeout" in err_lower or "timed out" in err_lower:
            raise HTTPException(
                status_code=status.HTTP_504_GATEWAY_TIMEOUT,
                detail=f"AI Tutor request timed out connecting to Gemini: {err_msg[:250]}. Please click Retry.",
            )
        if "429" in err_lower or "quota" in err_lower or "resource_exhausted" in err_lower:
            raise HTTPException(
                status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                detail=f"Gemini API rate limit reached: {err_msg[:250]}. Please wait a moment and click Retry.",
            )
        if "404" in err_lower:
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"Gemini model not found: {err_msg[:250]}. Please click Retry.",
            )
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"Gemini AI Tutor error ({type(e).__name__}): {err_msg[:300]}. Please click Retry.",
        )


